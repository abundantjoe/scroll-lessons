"""Facts sheet: every number the release documents quote, generated from the committed results files (never typed by hand).

  release_facts.py > results/FACTS.md

Reporting rule: values are TRUNCATED toward zero at 3 decimals (never rounded up); where a longer value is given beside it, it is
truncated at 6 decimals.
"""
import json, os, sys
sys.path.insert(0, ".")
from inkeval import trunc

T = lambda x: "n/a" if x is None else f"{trunc(x, 3):.3f}"
F = lambda x: "n/a" if x is None else f"{trunc(x, 6):.6f}"          # truncated at 6 decimals, never rounded up
NAMES = {"e": "E (v8 + GP-R1 ensemble)", "v8": "v8 2-D U-Net, 15 crops", "gpr1": "GP-R1 Grand-Prize-style 3-D->2-D",
         "v6b": "v6b U-Net, 8 crops, team-vetoed", "v6c": "v6c U-Net, 8 crops (control)", "v7": "v7 hand-built ridge",
         "v3": "v3 hand-built ridge (66 features)", "v2": "v2 band-passed depth template", "v1b": "v1b depth template",
         "v0.1b": "v0.1b papyrus subtraction", "team": "team 2.4 um model (positive control)"}


def table(path, title):
    if not os.path.exists(path):
        print(f"\n## {title}\n\n(not yet computed: {path})"); return
    r = json.load(open(path))
    print(f"\n## {title}\n\nsource: `{path}`; crops: {', '.join(r['crops'])}; effective n: {r['effective_n']}; "
          f"bootstrap: {r['bootstrap']}\n")
    print("| method | pixel AUC [95% CI] | stroke AUC [95% CI] | local L [95% CI] | pixel mean (6 decimals, truncated) |")
    print("|---|---|---|---|---|")
    for m, s in r["summary"].items():
        def c(k):
            x = s.get(k)
            if not x or "mean" not in x: return "n/a"
            return f"{T(x['mean'])} [{T(x['ci95'][0])}, {T(x['ci95'][1])}]"
        print(f"| {NAMES.get(m, m)} | {c('pixel')} | {c('stroke')} | {c('local')} | {F((s.get('pixel') or {}).get('mean'))} |")
    print("\nper-crop pixel / stroke / local:\n")
    for m, rows in r["per_crop"].items():
        print(f"- {m}: " + "; ".join(f"{x['crop']} {T(x['pixel'])}/{T(x['stroke'])}/{T(x['local'])}" for x in rows))
    print("\npaired differences (mean [95% CI], crops positive / n):\n")
    for k, v in r["paired_differences"].items():
        print(f"- {k}: " + "; ".join(f"{met} {T(x['mean'])} [{T(x['ci95'][0])}, {T(x['ci95'][1])}] {x['positive_crops']}/{x['n']}"
                                     for met, x in v.items()))
    print("\nnegative control, label-swap null (pixel AUC over ordered crop pairs):\n")
    for k, v in r["negative_control_label_swap"].items():
        print(f"- {k}: mean {T(v['mean'])} (6 decimals {F(v['mean'])}), range [{T(v['min'])}, {T(v['max'])}], pairs {v['pairs']}")


print("# Release facts (generated by scripts/release_facts.py from committed results; do not edit by hand)")
table("results/stats_evaluation7.json", "Evaluation set: 7 held-out crops (pre-registered methods; v0.1b, v1b, v2, v3 and the team model re-judged under mask J and the stroke test, the others judged once)")
table("results/stats_confirmation.json", "Confirmation set C1: untouched crops (pre-registered 2026-10-15, frozen weights; v1b is computed by crop preparation and is not a declared C1 method)")
if os.path.exists("results/d3_decomposition.json"):
    r = json.load(open("results/d3_decomposition.json"))
    print("\n## D3 post-hoc decomposition (ensembling vs smoothing), 7 evaluation crops\n")
    for k, s in r["summary"].items():
        print(f"- {k}: " + "; ".join(f"{met} {T(x['mean'])} [{T(x['ci'][0])}, {T(x['ci'][1])}]" for met, x in s.items()))
    for k, v in r["paired_differences"].items():
        print(f"- diff {k}: " + "; ".join(f"{met} {T(x['mean'])} [{T(x['ci'][0])}, {T(x['ci'][1])}] {x['positive_units']}/{x['n']}" for met, x in v.items()))
if os.path.exists("results/n1_reading_null.json"):
    r = json.load(open("results/n1_reading_null.json"))
    print("\n## N1 post-hoc null for the reading-run agreement statistic (unread windows)\n")
    for t, v in r["tags"].items():
        print(f"- {t}: matched " + ", ".join(f"{k} {T(x)}" for k, x in v["matched"].items())
              + f"; null mean {T(v['null_mean'])}, range [{T(v['null_min'])}, {T(v['null_max'])}] over {len(v['null_values'])} pairs; "
              f"matched above null max: {v['matched_above_null_max']}/4")
if os.path.exists("results/preregistration_order.json"):
    print("\n## Pre-registration order (git)\n")
    for x in json.load(open("results/preregistration_order.json")):
        print(f"- {x['test']}: declared {x['declared_commit']} {x['declared_time']} -> result {x['result_commit']} {x['result_time']}: {x['order']}")
